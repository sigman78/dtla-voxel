import { BALANCED_PROFILE } from '../src/performanceProfile.ts';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { stripTypeScriptTypes } from 'node:module';
import * as THREE from 'three';
let source=fs.readFileSync('src/shadowTiles.ts','utf8');
source=source.replace(/constructor\(([\s\S]*?)\) \{/g,(_,params)=>{
  const fields=[...params.matchAll(/(?:private )?readonly (\w+)/g)].map(m=>m[1]);
  return `constructor(${params.replace(/(?:private )?readonly /g,'')}) {${fields.map(f=>`this.${f}=${f};`).join('')}`;
});
const ctx=vm.createContext({THREE,BALANCED_PROFILE});
vm.runInContext(stripTypeScriptTypes(source).replace(/^import[\s\S]*?;\s*$/gm,'').replace(/^export /gm,'')+'\nglobalThis.ShadowTiles=ShadowTiles;',ctx);
const meta={H:100}, scene=new THREE.Scene(), camera=new THREE.PerspectiveCamera();
const S={nodes:new Map(),shadowKeys:new Set(),group:new THREE.Group(),bounds:(s,x,z)=>[x*s*128,z*s*128,(x+1)*s*128,(z+1)*s*128]};
const root={key:'2/0_0',s:2,tx:0,ty:0,children:[],score:0};
S.foliageKey=(x,y)=>`f/${x}_${y}`;
for(let y=0;y<2;y++)for(let x=0;x<2;x++)root.children.push({key:`1/${x}_${y}`,s:1,tx:x,ty:y,children:[],score:0});
for(const n of [root,...root.children]){
  const mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshBasicMaterial());
  mesh.customDepthMaterial=new THREE.MeshDepthMaterial();mesh.customDistanceMaterial=new THREE.MeshDistanceMaterial();mesh.visible=false;
  S.nodes.set(n.key,{state:'ready',mesh});
  if(n.s===1)S.nodes.set(S.foliageKey(n.tx,n.ty),{state:'ready'});
}
let shadow, fail=false, calls=0;
let restore;
const renderer={domElement:{addEventListener(_name,fn){restore=fn;}},shadowMap:{render(){calls++;assert.equal(shadow.group.visible,S.group.visible);if(fail)throw new Error('test');}}};
shadow=new ctx.ShadowTiles(S,meta,renderer,scene);
camera.position.set(128,1000,128);
assert.equal(shadow.update([root],camera),true);
assert.deepEqual([...S.shadowKeys],['2/0_0']);
assert.equal(shadow.group.visible,false);
const proxy=shadow.group.children[0],original=S.nodes.get(root.key).mesh;
assert.equal(proxy.geometry,original.geometry,'no duplicate GPU buffer');
assert.equal(proxy.customDepthMaterial,original.customDepthMaterial);
assert.equal(proxy.customDistanceMaterial,original.customDistanceMaterial);
assert.equal(shadow.update([root],camera),false,'stable coarse casters do not invalidate shadows');
renderer.shadowMap.render();assert.equal(shadow.group.visible,false);
fail=true;assert.throws(()=>renderer.shadowMap.render());assert.equal(shadow.group.visible,false,'restored after render failure');fail=false;
S.group.visible=false;renderer.shadowMap.render();S.group.visible=true;
camera.position.y=280;shadow.update([root],camera);
assert.equal(S.shadowKeys.size,4,'near camera gets exact geometry');
camera.position.y=320;shadow.update([root],camera);assert.equal(S.shadowKeys.size,4,'exit band holds near detail');
camera.position.y=370;shadow.update([root],camera);assert.deepEqual([...S.shadowKeys],['2/0_0']);
camera.position.y=280;S.nodes.get(root.children[0].key).state='loading';
shadow.update([root],camera);assert.deepEqual([...S.shadowKeys],['2/0_0'],'parent retained until all children ready');
S.nodes.get(root.children[0].key).state='ready';shadow.update([root],camera);assert.equal(S.shadowKeys.size,4);
shadow.update([],camera);assert.equal(shadow.group.children.length,0);assert.equal(S.shadowKeys.size,0);
assert.equal(calls,3);
renderer.shadowMap={render(){assert.equal(shadow.group.visible,true);}};
restore();renderer.shadowMap.render();assert.equal(shadow.group.visible,false);
console.log('Passed: shared geometry/depth materials, pass isolation, exception restore, near-detail hysteresis, atomic coverage and proxy release');
